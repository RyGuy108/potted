import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { AnchorProvider, BN, Program, type Idl, Wallet } from "@coral-xyz/anchor";
import {
  createAssociatedTokenAccountIdempotent,
  createTransferInstruction,
  getAccount,
  getAssociatedTokenAddressSync,
  getMint,
  mintTo,
  TokenAccountNotFoundError,
} from "@solana/spl-token";
import { Connection, Keypair, PublicKey, Transaction } from "@solana/web3.js";
import type { Challenge, Evidence } from "@potted/core";
import baseIdl from "./escrow-idl.json";
import type { Escrow } from "./escrow-types";
import type { Ledger, Payout } from "./ledger";
import { privySign, privyWalletId } from "./privy";

/**
 * The ledger backed by the escrow program on Solana.
 *
 * Wallets here are custodial: the server makes a keypair for each account
 * and signs for it, so fans need no wallet app and pay no fees. That suits
 * a devnet demo with test tokens and nothing more. Replacing it with
 * wallets the user controls (an embedded wallet) changes only how a
 * transaction is signed, not which instructions are sent.
 *
 * One server key does three jobs: it pays every fee and rent, it is the
 * verifier the program accepts results from, and it is the mint authority
 * of the test USDC that the faucet hands out.
 */

const VERIFIER_KINDS: Record<string, number> = { lichess: 0, brawlstars: 1, fortnite: 2, optimistic: 3, steam: 4, twitch: 5 };

function required(name: string): string {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is not set. See docs/keys.md.`);
  return value;
}

/** Accepts a keypair as solana-keygen writes it: a JSON array of 64 numbers. */
export function keypairFromEnv(name: string): Keypair {
  const raw = required(name).trim();
  try {
    return Keypair.fromSecretKey(Uint8Array.from(JSON.parse(raw) as number[]));
  } catch {
    throw new Error(`${name} must be the contents of a keypair file, e.g. [12,34,...]`);
  }
}

/** The program's u64 challenge id, derived from the app's id so the account address is stable. */
export function chainId(challengeId: string): BN {
  return new BN(createHash("sha256").update(challengeId).digest().subarray(0, 8), "le");
}

const sha256 = (text: string) => [...createHash("sha256").update(text).digest()];
const seconds = (ms: number) => new BN(Math.floor(ms / 1000));

export class SolanaLedger implements Ledger {
  readonly kind = "solana" as const;
  readonly connection: Connection;
  readonly server: Keypair;
  readonly mint: PublicKey;
  readonly program: Program<Escrow>;
  private keys = new Map<string, Keypair>();
  private keyFile: string;

  constructor() {
    this.connection = new Connection(process.env.SOLANA_RPC_URL || "https://api.devnet.solana.com", "confirmed");
    this.server = keypairFromEnv("VERIFIER_SECRET_KEY");
    this.mint = new PublicKey(required("USDC_MINT"));
    // The IDL is generated by `anchor idl build`; the address is whatever you deployed.
    const idl = { ...(baseIdl as Idl), address: required("POTTED_PROGRAM_ID") } as unknown as Escrow;
    const provider = new AnchorProvider(this.connection, new Wallet(this.server), { commitment: "confirmed" });
    this.program = new Program(idl, provider);
    this.keyFile = path.join(process.env.POTTED_DATA_DIR || path.join(process.cwd(), ".data"), "wallets.json");
    this.loadKeys();
  }

  // --- Custodial wallets ---------------------------------------------------

  private loadKeys() {
    if (!fs.existsSync(this.keyFile)) return;
    const saved = JSON.parse(fs.readFileSync(this.keyFile, "utf8")) as Record<string, number[]>;
    for (const [address, secret] of Object.entries(saved)) {
      if (!this.keys.has(address)) this.keys.set(address, Keypair.fromSecretKey(Uint8Array.from(secret)));
    }
  }

  /**
   * Adds this process's keys to the file. Another process (the dev server
   * and the sample script, say) may have added keys since this one loaded,
   * so the file is read and merged first: a key is never dropped.
   */
  private saveKeys() {
    fs.mkdirSync(path.dirname(this.keyFile), { recursive: true });
    this.loadKeys();
    const out = Object.fromEntries([...this.keys].map(([address, key]) => [address, [...key.secretKey]]));
    // Owner-only: these keys move the accounts' test tokens. Written through a temp file so a crash cannot truncate it.
    const tmp = `${this.keyFile}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, JSON.stringify(out), { mode: 0o600 });
    fs.renameSync(tmp, this.keyFile);
  }

  /** Whether this server can sign for a wallet (itself or through Privy), after checking the file for keys another process added. */
  hasKey(wallet: string): boolean {
    if (privyWalletId(wallet)) return true;
    if (!this.keys.has(wallet)) this.loadKeys();
    return this.keys.has(wallet);
  }

  newWallet(): string {
    const key = Keypair.generate();
    this.keys.set(key.publicKey.toBase58(), key);
    this.saveKeys();
    return key.publicKey.toBase58();
  }

  private signer(wallet: string): Keypair {
    if (!this.keys.has(wallet)) this.loadKeys();
    const key = this.keys.get(wallet);
    if (!key) throw new Error(`No key on this server for wallet ${wallet}`);
    return key;
  }

  /**
   * Signs and sends a transaction an account has to approve. The server
   * pays the fee. Each account signs with its key on this server, or Privy
   * signs for it when Privy holds the wallet.
   */
  private async sendAs(tx: Transaction, wallets: string[]): Promise<string> {
    const { blockhash, lastValidBlockHeight } = await this.connection.getLatestBlockhash("confirmed");
    tx.feePayer = this.server.publicKey;
    tx.recentBlockhash = blockhash;
    const held = wallets.filter((w) => privyWalletId(w));
    tx.partialSign(this.server, ...wallets.filter((w) => !privyWalletId(w)).map((w) => this.signer(w)));
    let signed = tx;
    for (const wallet of held) {
      const wire = signed.serialize({ requireAllSignatures: false, verifySignatures: false }).toString("base64");
      signed = Transaction.from(Buffer.from(await privySign(wallet, wire), "base64"));
    }
    const signature = await this.connection.sendRawTransaction(signed.serialize());
    const confirmed = await this.connection.confirmTransaction({ signature, blockhash, lastValidBlockHeight }, "confirmed");
    if (confirmed.value.err) throw new Error(`Transaction failed: ${JSON.stringify(confirmed.value.err)}`);
    return signature;
  }

  private tokenAccount(wallet: string | PublicKey): PublicKey {
    return getAssociatedTokenAddressSync(this.mint, new PublicKey(wallet), true);
  }

  private async ensureTokenAccount(wallet: string): Promise<PublicKey> {
    return createAssociatedTokenAccountIdempotent(this.connection, this.server, this.mint, new PublicKey(wallet), { commitment: "confirmed" });
  }

  // --- Addresses -----------------------------------------------------------

  private accountsFor(challenge: Challenge, streamerWallet?: string) {
    const streamer = new PublicKey(streamerWallet ?? challenge.ledgerRef?.split(":")[1] ?? "");
    const programId = this.program.programId;
    const [account] = PublicKey.findProgramAddressSync([Buffer.from("challenge"), streamer.toBuffer(), chainId(challenge.id).toArrayLike(Buffer, "le", 8)], programId);
    const [vault] = PublicKey.findProgramAddressSync([Buffer.from("vault"), account.toBuffer()], programId);
    return { streamer, account, vault };
  }

  private pledgeAddress(account: PublicKey, fan: PublicKey): PublicKey {
    return PublicKey.findProgramAddressSync([Buffer.from("pledge"), account.toBuffer(), fan.toBuffer()], this.program.programId)[0];
  }

  // --- Ledger ---------------------------------------------------------------

  async faucet(wallet: string, amountMicro: number): Promise<string> {
    const mint = await getMint(this.connection, this.mint);
    if (!mint.mintAuthority?.equals(this.server.publicKey)) {
      throw new Error("The faucet needs a test USDC mint that the server key controls. Run `pnpm --filter @potted/web solana:setup`.");
    }
    const to = await this.ensureTokenAccount(wallet);
    return mintTo(this.connection, this.server, this.mint, to, this.server, amountMicro, [], { commitment: "confirmed" });
  }

  async balanceOf(wallet: string): Promise<number> {
    if (wallet.startsWith("sim:")) return 0;
    try {
      return Number((await getAccount(this.connection, this.tokenAccount(wallet))).amount);
    } catch (error) {
      if (error instanceof TokenAccountNotFoundError) return 0;
      throw error;
    }
  }

  async createChallenge(challenge: Challenge, streamerWallet: string) {
    const { account, vault } = this.accountsFor(challenge, streamerWallet);
    const tx = await this.program.methods
      .createChallenge(
        chainId(challenge.id),
        VERIFIER_KINDS[challenge.condition.kind] ?? 3,
        sha256(JSON.stringify(challenge.condition)),
        seconds(challenge.deadline),
        seconds(challenge.settleBy),
        new BN(challenge.pledgeCapMicro),
        challenge.upfrontPct ?? 0,
      )
      .accountsPartial({
        payer: this.server.publicKey,
        streamer: new PublicKey(streamerWallet),
        verifier: this.server.publicKey,
        mint: this.mint,
        challenge: account,
        vault,
      })
      .transaction();
    const sent = await this.sendAs(tx, [streamerWallet]);
    // "<challenge account>:<streamer wallet>", so later calls can rebuild the addresses.
    return { ref: `${account.toBase58()}:${streamerWallet}`, tx: sent };
  }

  async pledge(challenge: Challenge, fanWallet: string, amountMicro: number): Promise<string> {
    const { account, vault } = this.accountsFor(challenge);
    const fan = new PublicKey(fanWallet);
    const tx = await this.program.methods
      .pledge(new BN(amountMicro))
      .accountsPartial({
        payer: this.server.publicKey,
        fan,
        challenge: account,
        pledge: this.pledgeAddress(account, fan),
        fanToken: this.tokenAccount(fan),
        vault,
      })
      .transaction();
    return this.sendAs(tx, [fanWallet]);
  }

  /** The program pays the up-front share to the host; guest and cause shares follow from the host. */
  async lock(challenge: Challenge, upfront: Payout[]): Promise<string> {
    const { streamer, account, vault } = this.accountsFor(challenge);
    for (const p of upfront) new PublicKey(p.wallet);
    const streamerToken = await this.ensureTokenAccount(streamer.toBase58());
    // The program accepts the verifier as well as the streamer here.
    const tx = await this.program.methods.lock().accountsPartial({ authority: this.server.publicKey, challenge: account, vault, streamerToken }).rpc();
    await this.sendShares(streamer, streamerToken, upfront);
    return tx;
  }

  /** A gift: test USDC straight from one custodial wallet to another, signed by the giver's key. */
  async transfer(fromWallet: string, toWallet: string, amountMicro: number): Promise<string> {
    const from = new PublicKey(fromWallet);
    const fromToken = this.tokenAccount(from);
    if ((await this.balanceOf(fromWallet)) < amountMicro) throw new Error("Not enough test USDC for that");
    const to = await this.ensureTokenAccount(toWallet);
    return this.sendAs(new Transaction().add(createTransferInstruction(fromToken, to, from, amountMicro)), [fromWallet]);
  }

  /** Sends guest and cause shares out of the host's wallet after the program has paid the host. */
  private async sendShares(host: PublicKey, hostToken: PublicKey, payouts: Payout[]): Promise<void> {
    const shares = payouts.filter((p) => p.wallet !== host.toBase58() && p.amountMicro > 0);
    if (shares.length === 0) return;
    const transfer = new Transaction();
    for (const share of shares) {
      const to = await this.ensureTokenAccount(share.wallet);
      transfer.add(createTransferInstruction(hostToken, to, host, share.amountMicro));
    }
    await this.sendAs(transfer, [host.toBase58()]);
  }

  /**
   * The program pays the whole pot to the host. Shares for a collab guest
   * or a cause are then sent from the host's wallet, which the server can
   * sign for because wallets are custodial in this mode. Splitting inside
   * the program, so no one has to be trusted with a share, is the
   * program-splits branch on the roadmap.
   */
  async settle(challenge: Challenge, success: boolean, evidence: Evidence | undefined, payouts: Payout[]): Promise<string> {
    const { streamer, account, vault } = this.accountsFor(challenge);
    // Check every share's address before anything is sent, so a bad one
    // cannot leave the pot paid to the host with the shares unpaid.
    for (const p of payouts) new PublicKey(p.wallet);
    const evidenceRef = (evidence?.ref ?? (success ? "settled" : "failed")).slice(0, 96);
    const streamerToken = await this.ensureTokenAccount(streamer.toBase58());
    const tx = await this.program.methods
      .settle(success, evidenceRef, sha256(JSON.stringify(evidence ?? null)))
      .accountsPartial({ verifier: this.server.publicKey, challenge: account, vault, streamerToken })
      .rpc();
    if (success) await this.sendShares(streamer, streamerToken, payouts);
    return tx;
  }

  /**
   * The program refunds a fan's whole pledge at once (less their share of
   * anything paid up front, which it works out itself). The app calls this
   * once per fan; a repeat finds it already done and returns a marker.
   */
  async refund(challenge: Challenge, fanWallet: string): Promise<string> {
    const { account, vault } = this.accountsFor(challenge);
    const fan = new PublicKey(fanWallet);
    const pledge = this.pledgeAddress(account, fan);
    const record = await this.program.account.pledge.fetchNullable(pledge);
    if (!record) throw new Error("No pledge on chain for this fan");
    if (record.refunded) return `included:${pledge.toBase58()}`;
    await this.ensureTokenAccount(fanWallet);
    return this.program.methods.refund().accountsPartial({ challenge: account, pledge, fanToken: this.tokenAccount(fan), vault }).rpc();
  }

  // --- Fan requests ------------------------------------------------------
  // The escrow program holds completion pledges. Request money has a
  // different rule (paid when the attempt starts, whatever the result), so
  // it is held in the server's own token account until the climber answers,
  // then sent on or back as ordinary USDC transfers, each with a receipt.

  async holdBacking(_bountyId: string, fanWallet: string, amountMicro: number): Promise<string> {
    return this.transfer(fanWallet, this.server.publicKey.toBase58(), amountMicro);
  }

  async returnBacking(_bountyId: string, fanWallet: string, amountMicro: number): Promise<string> {
    return this.fromServer(fanWallet, amountMicro);
  }

  async payBacking(_bountyId: string, climberWallet: string, amountMicro: number): Promise<string> {
    return this.fromServer(climberWallet, amountMicro);
  }

  private async fromServer(toWallet: string, amountMicro: number): Promise<string> {
    const from = this.tokenAccount(this.server.publicKey);
    const to = await this.ensureTokenAccount(toWallet);
    return this.sendAs(new Transaction().add(createTransferInstruction(from, to, this.server.publicKey, amountMicro)), []);
  }
}
