import { EVENT_LAYOUTS, discriminator } from "./events";

/**
 * Filters to paste into QuickNode Streams. They run inside QuickNode, on
 * every block, so the Stream delivers ready-made Potted events instead of
 * raw transactions. They are plain JavaScript with no Node APIs (no
 * Buffer, no imports), generated from the same event layouts the app
 * decodes with, so the two cannot drift apart.
 */

/** Shared helpers, as source: base64 to bytes, base58, little-endian reads. */
const HELPERS = `
  var B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  var B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
  function fromB64(text) {
    var clean = text.replace(/=+$/, "");
    var out = [];
    var buffer = 0, bits = 0;
    for (var i = 0; i < clean.length; i++) {
      var v = B64.indexOf(clean.charAt(i));
      if (v < 0) return null;
      buffer = (buffer << 6) | v;
      bits += 6;
      if (bits >= 8) {
        bits -= 8;
        out.push((buffer >> bits) & 255);
      }
    }
    return out;
  }
  function toB58(bytes) {
    var digits = [];
    for (var i = 0; i < bytes.length; i++) {
      var carry = bytes[i];
      for (var j = 0; j < digits.length; j++) {
        carry += digits[j] * 256;
        digits[j] = carry % 58;
        carry = Math.floor(carry / 58);
      }
      while (carry > 0) {
        digits.push(carry % 58);
        carry = Math.floor(carry / 58);
      }
    }
    var out = "";
    for (var k = 0; k < bytes.length && bytes[k] === 0; k++) out += "1";
    for (var m = digits.length - 1; m >= 0; m--) out += B58.charAt(digits[m]);
    return out;
  }
  function u32(b, at) { return b[at] + b[at + 1] * 256 + b[at + 2] * 65536 + b[at + 3] * 16777216; }
  function u64(b, at) { return u32(b, at) + u32(b, at + 4) * 4294967296; }
  function hex(b, from, to) {
    var s = "";
    for (var i = from; i < to; i++) s += (b[i] < 16 ? "0" : "") + b[i].toString(16);
    return s;
  }
`;

/**
 * The escrow Stream's filter: keeps successful transactions that ran the
 * escrow program and decodes its events right there. An event counts only
 * while the escrow program itself was executing, as in `decodeLogs`.
 */
export function escrowFilterSource(programId: string): string {
  const layouts: Record<string, { name: string; fields: readonly (readonly [string, string])[] }> = {};
  for (const [name, fields] of Object.entries(EVENT_LAYOUTS)) layouts[discriminator(name).toString("hex")] = { name, fields };
  return `// Potted escrow events, decoded inside QuickNode. Generated by @potted/chain; do not edit by hand.
function main(stream) {
  var PROGRAM_ID = ${JSON.stringify(programId)};
  var LAYOUTS = ${JSON.stringify(layouts)};
${HELPERS}
  function decode(bytes) {
    if (!bytes || bytes.length < 8) return null;
    var layout = LAYOUTS[hex(bytes, 0, 8)];
    if (!layout) return null;
    var fields = {}, at = 8;
    for (var i = 0; i < layout.fields.length; i++) {
      var field = layout.fields[i][0], type = layout.fields[i][1];
      if (type === "pubkey") {
        if (at + 32 > bytes.length) return null;
        fields[field] = toB58(bytes.slice(at, at + 32)); at += 32;
      } else if (type === "u64" || type === "i64") {
        if (at + 8 > bytes.length) return null;
        fields[field] = u64(bytes, at); at += 8;
      } else if (type === "bool") {
        fields[field] = bytes[at] === 1; at += 1;
      } else if (type === "shares") {
        var count = u32(bytes, at); at += 4;
        if (count > 8 || at + count * 33 > bytes.length) return null;
        var parts = [];
        for (var s = 0; s < count; s++) { parts.push(toB58(bytes.slice(at, at + 32)) + ":" + bytes[at + 32]); at += 33; }
        fields[field] = parts.join(",");
      } else {
        var len = u32(bytes, at); at += 4;
        if (at + len > bytes.length) return null;
        var text = "";
        for (var c = at; c < at + len; c++) text += String.fromCharCode(bytes[c]);
        fields[field] = decodeURIComponent(escape(text)); at += len;
      }
    }
    return { name: layout.name, challenge: fields.challenge, fields: fields };
  }
  var out = [];
  var blocks = Array.isArray(stream.data) ? stream.data : [stream.data];
  for (var bi = 0; bi < blocks.length; bi++) {
    var block = blocks[bi] || {};
    var txs = block.transactions || [];
    for (var ti = 0; ti < txs.length; ti++) {
      var tx = txs[ti];
      if (!tx || !tx.meta || tx.meta.err) continue;
      var logs = tx.meta.logMessages || [];
      var stack = [], events = [];
      for (var li = 0; li < logs.length; li++) {
        var line = logs[li];
        var invoke = /^Program (\\S+) invoke \\[\\d+\\]$/.exec(line);
        if (invoke) { stack.push(invoke[1]); continue; }
        if (/^Program \\S+ (success|failed)/.test(line)) { stack.pop(); continue; }
        if (line.indexOf("Program data: ") === 0 && stack[stack.length - 1] === PROGRAM_ID) {
          var event = decode(fromB64(line.slice(14)));
          if (event) events.push(event);
        }
      }
      if (events.length) {
        out.push({
          signature: tx.transaction.signatures[0],
          slot: block.slot || (block.parentSlot + 1),
          blockTime: block.blockTime,
          events: events,
        });
      }
    }
  }
  return out.length ? { data: out } : null;
}
`;
}

/**
 * The charity Stream's filter: any USDC that reaches one of the causes'
 * wallets, from the escrow program or from anyone else, read from the
 * transaction's token balances before and after.
 */
export function causeFilterSource(mint: string, causeWallets: readonly string[]): string {
  return `// Potted: USDC arriving at causes' wallets. Generated by @potted/chain; do not edit by hand.
function main(stream) {
  var MINT = ${JSON.stringify(mint)};
  var CAUSES = ${JSON.stringify([...new Set(causeWallets)])};
  var out = [];
  var blocks = Array.isArray(stream.data) ? stream.data : [stream.data];
  for (var bi = 0; bi < blocks.length; bi++) {
    var block = blocks[bi] || {};
    var txs = block.transactions || [];
    for (var ti = 0; ti < txs.length; ti++) {
      var tx = txs[ti];
      if (!tx || !tx.meta || tx.meta.err) continue;
      var before = {};
      var pre = tx.meta.preTokenBalances || [];
      for (var p = 0; p < pre.length; p++) {
        if (pre[p].mint === MINT) before[pre[p].accountIndex] = Number(pre[p].uiTokenAmount.amount);
      }
      var post = tx.meta.postTokenBalances || [];
      for (var q = 0; q < post.length; q++) {
        var bal = post[q];
        if (bal.mint !== MINT || CAUSES.indexOf(bal.owner) < 0) continue;
        var gained = Number(bal.uiTokenAmount.amount) - (before[bal.accountIndex] || 0);
        if (gained > 0) {
          out.push({ signature: tx.transaction.signatures[0], slot: block.slot || (block.parentSlot + 1), blockTime: block.blockTime, wallet: bal.owner, amount: gained });
        }
      }
    }
  }
  return out.length ? { data: out } : null;
}
`;
}
